//! The native executors of the differential harness, and the parity inventory.
//!
//! During the transition to native execution (`docs/roadmap/nexus/decisions.md`,
//! N6 and N14) an executable case is compared against one more executor: the
//! reference stepper. It lowers the checked program to execution IR, verifies
//! it, admits it, and steps it on Nexus with a fresh copy of the case's host
//! world under the runner's memory limit, twice: unbounded, and with quota 1.
//! Both runs are held to the case's one expectation, by the comparison the Wasm
//! backend uses.
//!
//! The stepper reports in the terms of [`WasmObservation`]: it completed with a
//! canonical result and an audit trace, it trapped with a code, it ended in the
//! host event, or it failed.
//!
//! # What a stepper run observes
//!
//! The result of the entry, read from the store by the entry's result type for
//! the value kinds the lowering can produce today (scalars, `bool`, `str`,
//! `atom`, `bytes`, records, tuples, enums, wrappers, unions, and arrays), and
//! encoded by `ObservedValue`, the encoder every other executor uses; whether
//! the entry returned `err`; the audit trace; a trap's code; and the host
//! event. A result of another kind (a dict, a function behind an interface, a
//! value nested deeper than the reader follows) cannot be observed yet, and a
//! case that needs one is `pending X3-18`. The origin of a trap is not
//! compared, because no expectation states one and the other executors do not
//! compare it. The arena balance that the Wasm backend checks is not checked:
//! the context does not expose what its module values keep.
//!
//! A test suite (`workspace-test`) needs the test table and the harness test
//! runs, which are package X3-18, so its cases are `pending` there or at the
//! package that owns the first form a test needs.
//!
//! # The inventory
//!
//! `conformance/native-parity.tsv` has one row for each executable case. Its
//! columns are `case`, `stepper`, `windows`, `linux`, and `macos`; a cell is
//! `matched`, or `pending` and the identifier of the package that will move it.
//! Only the `stepper` column is executable today. The file is generated by
//! `vibra-conformance --write-native-parity <path>` and is never written by
//! the test suite; the committed file is the source of truth.

