/// The package that owns the observation of values and the test table.
const OBSERVATION: &str = "X3-18";

/// The package that owns the form a lowering refuses by `name`, or that owns
/// the stepper's refusal of an instruction by `name`; `None` for a name no
/// package owns.
///
/// This is the one mapping of the harness. The slice list in the module
/// documentation of `vibra-lower` and the feature table of
/// `docs/roadmap/nexus/plan-v0.0.3.md` say which package lowers each form.
#[must_use]
pub fn owning_package(name: &str) -> Option<&'static str> {
    Some(match name {
        form::EXTERNAL_NUMERIC | "intrinsic" => "X3-10",
        form::RECORD
        | form::VARIANT
        | form::WRAP
        | form::PROJECT
        | form::TUPLE
        | form::TUPLE_PROJECT
        | form::ARRAY
        | form::WIDEN => "X3-11",
        form::MATCH | form::TRY => "X3-12",
        form::GENERIC_ACTIVATION => "X3-13",
        form::DEFAULT | form::LABELLED_OR_VARIADIC_PARAMETER => "X3-14",
        form::CONTRACT_CALL => "X3-15",
        form::EXTERNAL_COLLECTION | form::DICT | form::LOOKUP => "X3-16",
        form::TEST_ASSERTION => OBSERVATION,
        // No checked entry takes a parameter; the entry's invocation and
        // outcome belong with the host operations.
        form::ENTRY_WITH_PARAMETERS => "X3-19",
        _ => return None,
    })
}

/// One run of the stepper.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct StepperRun {
    /// The quota of the run: [`u64::MAX`] for unbounded.
    pub quota: u64,
    /// What the run observed, in the terms the Wasm backend uses.
    pub observation: BackendObservation<WasmObservation>,
    /// The origin ordinal of the trap that ended the run, when one did.
    pub trap_origin: Option<u32>,
}

/// What the `windows` column needs of an accepted executable case: the checked
/// program to build, and the text of the host world the harness launcher reads
/// from standard input.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EntryJob {
    /// The checked program of the entry.
    pub program: CheckedProgram,
    /// The `@host-world.v1` document the executable is given.
    pub world_text: String,
}

/// The world of a run that names none: the default world.
pub(crate) const DEFAULT_WORLD_TEXT: &str = "(record format: @host-world.v1)\n";

/// The job for `program`, in the case's own host world when `case_world`, and
/// in the default world otherwise.
pub(crate) fn entry_job(
    case: &crate::corpus::Case,
    program: &CheckedProgram,
    case_world: bool,
) -> Option<Box<EntryJob>> {
    let world_text = match (case_world, case.manifest().inputs.host_world.as_deref()) {
        (true, Some(path)) => case.read_file(path).ok()?,
        _ => DEFAULT_WORLD_TEXT.to_owned(),
    };
    Some(Box::new(EntryJob {
        program: program.clone(),
        world_text,
    }))
}

/// What the stepper did with an accepted executable case.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum NativeObservation {
    /// The stepper cannot run the case yet: the package that will let it, and
    /// the form that stopped it.
    Pending {
        /// The owning package.
        package: String,
        /// The form or capability that stopped the stepper.
        form: String,
    },
    /// The stepper ran the case, unbounded and with quota 1.
    Ran(Vec<StepperRun>),
}

impl NativeObservation {
    fn pending(package: &str, form: &str) -> Self {
        Self::Pending {
            package: package.to_owned(),
            form: form.to_owned(),
        }
    }
}

/// The stepper's status on one executable case.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum NativeStatus {
    /// Both runs reproduced the case's one expectation.
    Matched,
    /// The stepper cannot run the case until the package lands.
    Pending(String),
    /// The stepper ran the case and disagreed, or the lowering failed.
    Failed {
        /// A stable, actionable explanation.
        reason: String,
    },
}

/// The stepper's counts over the executable cases.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct NativeCounts {
    /// Cases the stepper reproduced.
    pub matched: usize,
    /// Cases the stepper cannot run yet.
    pub pending: usize,
    /// Cases on which the stepper disagreed.
    pub failed: usize,
}

/// Lowers `program`, verifies and admits it, and steps its entry twice with a
/// fresh copy of `world`.
pub(crate) fn observe_entry(
    program: &CheckedProgram,
    world: &HostWorld,
) -> NativeObservation {
    let lowered = match lower(program) {
        Ok(lowered) => lowered,
        Err(LowerError::NotLowered(name)) => return refused(name),
        Err(other) => return failed(format!("the lowering failed: {other}")),
    };
    if let Err(error) = verify(&lowered) {
        return failed(format!(
            "the lowering produced invalid execution IR: {error}"
        ));
    }
    let code = match Evaluator::new(&lowered) {
        Ok(code) => code,
        Err(EvalError::Unsupported(name)) => return refused(name),
        Err(EvalError::Invalid(error)) => {
            return failed(format!("the stepper refused verified IR: {error}"));
        }
    };
    if let Err(error) = admit(&code.requirements()) {
        return failed(format!("admission refused the program: {error:?}"));
    }
    let mut runs = Vec::new();
    for quota in [UNBOUNDED, 1] {
        match step(&code, program, world, quota) {
            Ok((observation, trap_origin)) => runs.push(StepperRun {
                quota,
                observation,
                trap_origin,
            }),
            Err(name) => return NativeObservation::pending(OBSERVATION, name),
        }
    }
    NativeObservation::Ran(runs)
}

/// The stepper's observation of a test suite: every test program is lowered,
/// and the suite needs the test table and the harness test runs besides.
pub(crate) fn observe_tests<'p>(
    programs: impl IntoIterator<Item = &'p CheckedProgram>,
) -> NativeObservation {
    for program in programs {
        match lower(program) {
            Ok(_) => {}
            Err(LowerError::NotLowered(name)) => return refused(name),
            Err(other) => return failed(format!("the lowering failed: {other}")),
        }
    }
    NativeObservation::pending(OBSERVATION, "the test table and the test runs")
}

fn refused(name: &str) -> NativeObservation {
    match owning_package(name) {
        Some(package) => NativeObservation::pending(package, name),
        None => failed(format!("no package owns the form `{name}`")),
    }
}

fn failed(reason: String) -> NativeObservation {
    NativeObservation::Ran(vec![StepperRun {
        quota: UNBOUNDED,
        observation: BackendObservation::new(WasmObservation::Failed { reason }),
        trap_origin: None,
    }])
}

/// One run to the end, continuing after every yield. `Err` names a result the
/// reader cannot observe yet.
fn step(
    code: &Evaluator<'_>,
    program: &CheckedProgram,
    world: &HostWorld,
    quota: u64,
) -> Result<(BackendObservation<WasmObservation>, Option<u32>), &'static str> {
    let mut origin = None;
    let observation = step_run(code, program, world, quota, &mut origin)?;
    Ok((observation, origin))
}

fn step_run(
    code: &Evaluator<'_>,
    program: &CheckedProgram,
    world: &HostWorld,
    quota: u64,
    origin: &mut Option<u32>,
) -> Result<BackendObservation<WasmObservation>, &'static str> {
    let limit = u64::try_from(INSTANCE_MEMORY_LIMIT_BYTES).unwrap_or(u64::MAX);
    let mut host = WorldProvider::new(world);
    let mut ctx = Context::new(limit, code.globals(), &mut host);
    let memory_exhausted = || {
        BackendObservation::new(WasmObservation::HostEvent(
            DiagnosticCode::RuntimeMemoryExhausted.as_atom().to_owned(),
        ))
    };
    match code.start(&mut ctx) {
        Ok(()) => {}
        Err(Halt::Exhausted) => return Ok(memory_exhausted()),
        Err(_) => return Ok(defect("the entry frame could not be pushed")),
    }
    let outcome = loop {
        match run(&mut ctx, code, quota) {
            Outcome::Yielded => {}
            other => break other,
        }
    };
    match outcome {
        Outcome::Completed => {
            let result_type = program.entry().signature().result();
            let result = ctx.result();
            let value = read(
                ctx.store(),
                &program
                    .types()
                    .iter()
                    .map(|definition| (definition.id(), definition))
                    .collect(),
                result,
                &result_type,
                0,
            );
            let value = match value {
                Ok(value) => value,
                Err(Stop::Unobservable(what)) => return Err(what),
                Err(Stop::Fault(cause)) => {
                    return Ok(defect(&format!("the result is unreadable: {cause}")));
                }
            };
            if let Err(error) = ctx.store().drop_cell(result) {
                return Ok(defect(&format!("the result is not released: {error:?}")));
            }
            let audit_trace = ctx.audit().to_vec();
            let program_failed = value.is_err_variant();
            Ok(BackendObservation {
                outcome: WasmObservation::Completed(ExecutionObservation {
                    result: Some(value.canonical_observation(&result_type)),
                    audit_trace,
                }),
                program_failed: Some(program_failed),
            })
        }
        Outcome::Trapped(trap) => {
            if trap.code == vibra_ir::boundary::TrapCode::InvalidCheckedProgram {
                return Ok(defect("the stepper trapped on a verified program"));
            }
            *origin = Some(trap.origin);
            Ok(BackendObservation::new(WasmObservation::Trapped(
                trap.code.diagnostic_code().as_atom().to_owned(),
            )))
        }
        Outcome::MemoryExhausted => Ok(memory_exhausted()),
        _ => Ok(defect(
            "the dispatcher ended in a way this harness does not know",
        )),
    }
}

fn defect(cause: &str) -> BackendObservation<WasmObservation> {
    BackendObservation::new(WasmObservation::Failed {
        reason: format!(
            "{}: {cause}",
            vibra_ir::boundary::TrapCode::InvalidCheckedProgram
                .diagnostic_code()
                .as_atom()
        ),
    })
}

// -- reading a result ---------------------------------------------------------------

/// Why a result was not read.
enum Stop {
    /// The reader has no row for the value yet.
    Unobservable(&'static str),
    /// The store does not hold what the type says.
    Fault(String),
}

/// The deepest value the reader follows. A value is read by explicit recursion
/// over its type, and a deeper one waits for the observer of package X3-18.
const MAX_DEPTH: usize = 64;

type Definitions<'a> = BTreeMap<&'a TypeId, &'a TypeDefinition>;

fn fault(what: &str) -> Stop {
    Stop::Fault(what.to_owned())
}

/// The value `cell` holds, read by `ty`. The cell stays owned by the caller.
fn read(
    store: &Store,
    definitions: &Definitions<'_>,
    cell: Cell,
    ty: &Type,
    depth: usize,
) -> Result<ObservedValue, Stop> {
    if depth > MAX_DEPTH {
        return Err(Stop::Unobservable("a value nested deeper than the reader"));
    }
    let word =
        || u32::try_from(cell.bits & 0xFFFF_FFFF).map_err(|_| fault("a scalar cell"));
    let reference = || {
        cell.as_ref()
            .ok_or_else(|| fault("a scalar where a value is stored"))
    };
    let store_fault = |_| fault("a handle the store does not admit");
    let primitive = |value| Ok(ObservedValue::Primitive(value));
    let narrow = |what: &str| fault(&format!("a cell that does not fit {what}"));
    match ty {
        Type::Void => primitive(Value::Void),
        Type::Bool => {
            let value = reference()?;
            match store.variant(value).map_err(store_fault)? {
                0 => primitive(Value::Bool(false)),
                1 => primitive(Value::Bool(true)),
                _ => Err(fault("a bool with another variant")),
            }
        }
        Type::Char => primitive(Value::Char(
            char::from_u32(word()?).ok_or_else(|| narrow("a char"))?,
        )),
        Type::I8 => primitive(Value::I8(
            i8::try_from(word()?.cast_signed()).map_err(|_| narrow("i8"))?,
        )),
        Type::I16 => primitive(Value::I16(
            i16::try_from(word()?.cast_signed()).map_err(|_| narrow("i16"))?,
        )),
        Type::I32 => primitive(Value::I32(word()?.cast_signed())),
        Type::U8 => {
            primitive(Value::U8(u8::try_from(word()?).map_err(|_| narrow("u8"))?))
        }
        Type::U16 => primitive(Value::U16(
            u16::try_from(word()?).map_err(|_| narrow("u16"))?,
        )),
        Type::U32 => primitive(Value::U32(word()?)),
        Type::I64 => primitive(Value::I64(cell.bits.cast_signed())),
        Type::U64 => primitive(Value::U64(cell.bits)),
        Type::F32 => primitive(Value::F32(vibra_ir::canonical_f32_bits(word()?))),
        Type::F64 => primitive(Value::F64(vibra_ir::canonical_f64_bits(cell.bits))),
        Type::Str => {
            primitive(Value::Str(store.text(reference()?).map_err(store_fault)?))
        }
        Type::Atom | Type::AtomSingleton(_) => {
            primitive(Value::Atom(store.text(reference()?).map_err(store_fault)?))
        }
        Type::Bytes => primitive(Value::Bytes(
            store.byte_values(reference()?).map_err(store_fault)?,
        )),
        Type::Never
        | Type::Function(_)
        | Type::Param(_)
        | Type::Dict(..)
        | Type::Interface(..)
        | Type::Any => Err(Stop::Unobservable("a result of a kind the reader lacks")),
        Type::Array(element) => {
            let value = reference()?;
            let length = store.len(value).map_err(store_fault)?;
            let mut elements = Vec::new();
            for index in 0..length {
                let item = store.cell(value, index).map_err(store_fault)?;
                elements.push(read(store, definitions, item, element, depth + 1)?);
            }
            Ok(ObservedValue::Array(elements))
        }
        Type::Declared(_)
        | Type::Applied(..)
        | Type::Record(_)
        | Type::Enum(_)
        | Type::Tuple(_)
        | Type::Union(_) => {
            let body = match ty {
                Type::Declared(id) => definitions
                    .get(id)
                    .and_then(|definition| definition.instantiate(&[])),
                Type::Applied(id, arguments) => definitions
                    .get(id)
                    .and_then(|definition| definition.instantiate(arguments)),
                Type::Record(fields) => Some(TypeBody::Record(fields.clone())),
                Type::Enum(variants) => Some(TypeBody::Enum(variants.clone())),
                Type::Tuple(components) => Some(TypeBody::Tuple(components.clone())),
                _ => match ty {
                    Type::Union(members) => Some(TypeBody::Union(members.clone())),
                    _ => None,
                },
            }
            .ok_or_else(|| fault("a type with no declaration"))?;
            let type_id = match ty {
                Type::Declared(id) | Type::Applied(id, _) => Some(id.clone()),
                _ => None,
            };
            read_body(store, definitions, reference()?, body, type_id, depth)
        }
    }
}

fn read_body(
    store: &Store,
    definitions: &Definitions<'_>,
    value: vibra_nexus::Ref,
    body: TypeBody,
    type_id: Option<TypeId>,
    depth: usize,
) -> Result<ObservedValue, Stop> {
    let store_fault = |_| fault("a handle the store does not admit");
    let component = |index: usize, ty: &Type| {
        let index = u32::try_from(index).map_err(|_| fault("too many components"))?;
        let item = store.cell(value, index).map_err(store_fault)?;
        read(store, definitions, item, ty, depth + 1)
    };
    Ok(match body {
        TypeBody::Record(fields) => {
            let mut read_fields = Vec::new();
            for (index, (name, ty)) in fields.iter().enumerate() {
                read_fields.push((name.clone(), component(index, ty)?));
            }
            ObservedValue::Record {
                type_id,
                fields: read_fields,
            }
        }
        TypeBody::Tuple(components) => {
            let mut values = Vec::new();
            for (index, ty) in components.iter().enumerate() {
                values.push(component(index, ty)?);
            }
            ObservedValue::Tuple { type_id, values }
        }
        TypeBody::Wrapper(representation) => ObservedValue::Wrapper {
            type_id: type_id.ok_or_else(|| fault("a wrapper with no declaration"))?,
            value: Box::new(component(0, &representation)?),
        },
        TypeBody::Enum(variants) => {
            let chosen = usize::try_from(store.variant(value).map_err(store_fault)?)
                .map_err(|_| fault("a variant index"))?;
            let (name, payload) = variants
                .get(chosen)
                .ok_or_else(|| fault("an enum with a variant it does not declare"))?;
            let payload = if *payload == Type::Void {
                None
            } else {
                Some(Box::new(component(0, payload)?))
            };
            ObservedValue::Enum {
                type_id,
                variant: name.clone(),
                payload,
            }
        }
        TypeBody::Union(members) => {
            let chosen = usize::try_from(store.variant(value).map_err(store_fault)?)
                .map_err(|_| fault("a member index"))?;
            let member = members
                .get(chosen)
                .ok_or_else(|| fault("a union with a member it does not declare"))?;
            ObservedValue::Union {
                type_id,
                member: Box::new(member.clone()),
                value: Box::new(component(0, member)?),
            }
        }
    })
}

// -- the inventory ------------------------------------------------------------------

/// The columns of the inventory after `case`, in order.
pub const COLUMNS: [&str; 4] = ["stepper", "windows", "linux", "macos"];

/// The file name of the inventory, beside the corpus directory.
pub const INVENTORY_FILE: &str = "native-parity.tsv";

/// One cell of the inventory.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum InventoryCell {
    /// The executor reproduces the case's expectation.
    Matched,
    /// The executor does not run the case yet; the package that will move it.
    Pending(String),
}

impl InventoryCell {
    fn parse(text: &str) -> Result<Self, String> {
        if text == "matched" {
            return Ok(Self::Matched);
        }
        match text.strip_prefix("pending ") {
            Some(package)
                if !package.is_empty()
                    && package
                        .chars()
                        .all(|c| c.is_ascii_alphanumeric() || c == '-') =>
            {
                Ok(Self::Pending(package.to_owned()))
            }
            _ => Err(format!(
                "`{text}` is neither `matched` nor `pending <package>`"
            )),
        }
    }

    fn render(&self) -> String {
        match self {
            Self::Matched => "matched".to_owned(),
            Self::Pending(package) => format!("pending {package}"),
        }
    }
}

/// One row: a case and its cell for each of [`COLUMNS`].
pub type InventoryRow = (String, [InventoryCell; 4]);

/// The native parity inventory.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Inventory {
    rows: Vec<InventoryRow>,
}

impl Inventory {
    /// Decodes the text of the inventory file.
    ///
    /// # Errors
    ///
    /// The first line that is not a header, or a row of five tab-separated
    /// fields whose last four are cells.
    pub fn parse(text: &str) -> Result<Self, String> {
        let mut lines = text.lines();
        let header = format!("case\t{}", COLUMNS.join("\t"));
        if lines.next() != Some(header.as_str()) {
            return Err(format!("the header is not `{header}`"));
        }
        let mut rows = Vec::new();
        for (number, line) in (2_usize..).zip(lines) {
            let fields = line.split('\t').collect::<Vec<_>>();
            let [case, stepper, windows, linux, macos] = fields.as_slice() else {
                return Err(format!(
                    "line {number}: expected five tab-separated fields"
                ));
            };
            let cell = |text: &str| {
                InventoryCell::parse(text)
                    .map_err(|error| format!("line {number}: {error}"))
            };
            rows.push((
                (*case).to_owned(),
                [cell(stepper)?, cell(windows)?, cell(linux)?, cell(macos)?],
            ));
        }
        Ok(Self { rows })
    }

    /// Builds an inventory from rows.
    #[must_use]
    pub const fn from_rows(rows: Vec<InventoryRow>) -> Self {
        Self { rows }
    }

    /// The rows in file order.
    #[must_use]
    pub fn rows(&self) -> &[InventoryRow] {
        &self.rows
    }

    /// The rows in file order, mutably.
    pub fn rows_mut(&mut self) -> &mut Vec<InventoryRow> {
        &mut self.rows
    }

    /// The text of the file: a header and one row for each case, LF only.
    #[must_use]
    pub fn render(&self) -> String {
        let mut text = format!("case\t{}\n", COLUMNS.join("\t"));
        for (case, cells) in &self.rows {
            text.push_str(case);
            for cell in cells {
                text.push('\t');
                text.push_str(&cell.render());
            }
            text.push('\n');
        }
        text
    }

    /// The inventory the current executors produce: the stepper's cell is what
    /// it did, and each platform cell is pending at the package that will move
    /// it: the stepper's package, or `X3-09` for a case the stepper matches.
    #[must_use]
    pub fn generated(statuses: &[(String, NativeStatus)]) -> Self {
        Self::generated_with(statuses, None)
    }

    /// As [`Self::generated`], with the `windows` cell of each case taken from
    /// what the linked executables did when they were run: `matched`, or pending
    /// at the package that holds it.
    #[must_use]
    pub fn generated_with(
        statuses: &[(String, NativeStatus)],
        windows: Option<&[(String, NativeStatus)]>,
    ) -> Self {
        let mut rows = statuses
            .iter()
            .map(|(case, status)| {
                let stepper = match status {
                    NativeStatus::Pending(package) => {
                        InventoryCell::Pending(package.clone())
                    }
                    NativeStatus::Matched | NativeStatus::Failed { .. } => {
                        InventoryCell::Matched
                    }
                };
                let platform = match &stepper {
                    InventoryCell::Pending(package) => package.clone(),
                    InventoryCell::Matched => "X3-09".to_owned(),
                };
                let cell = || InventoryCell::Pending(platform.clone());
                let windows_cell = match windows
                    .and_then(|all| all.iter().find(|(name, _)| name == case))
                {
                    Some((_, NativeStatus::Matched)) => InventoryCell::Matched,
                    Some((_, NativeStatus::Pending(package))) => {
                        InventoryCell::Pending(package.clone())
                    }
                    _ => cell(),
                };
                (case.clone(), [stepper, windows_cell, cell(), cell()])
            })
            .collect::<Vec<_>>();
        rows.sort_by(|left, right| left.0.cmp(&right.0));
        Self { rows }
    }

    /// What is wrong with the table as a table, against the ids of the
    /// executable cases: a case with no row, a row with no case, a duplicate,
    /// and rows out of order.
    #[must_use]
    pub fn problems(&self, executable: &[String]) -> Vec<String> {
        let mut problems = Vec::new();
        let mut previous: Option<&str> = None;
        for (case, _) in &self.rows {
            if let Some(before) = previous {
                if before == case {
                    problems.push(format!("`{case}` has two rows"));
                } else if before > case.as_str() {
                    problems.push(format!("`{case}` is out of order after `{before}`"));
                }
            }
            previous = Some(case);
            if !executable.contains(case) {
                problems
                    .push(format!("`{case}` has a row and is not an executable case"));
            }
        }
        for case in executable {
            if !self.rows.iter().any(|(row, _)| row == case) {
                problems.push(format!("`{case}` is an executable case with no row"));
            }
        }
        problems
    }

    /// Where the `stepper` column disagrees with what the stepper did: a
    /// `matched` cell whose case does not match, and a `pending` cell whose
    /// case matches or is held by another package.
    #[must_use]
    pub fn stepper_disagreements(
        &self,
        statuses: &[(String, NativeStatus)],
    ) -> Vec<String> {
        self.column_disagreements(0, "the stepper", statuses)
    }

    /// As [`Self::stepper_disagreements`] for the `windows` column against what
    /// the linked executables did, and one more rule: a row `matched` in
    /// `windows` must be `matched` in `stepper`.
    #[must_use]
    pub fn windows_disagreements(
        &self,
        statuses: &[(String, NativeStatus)],
    ) -> Vec<String> {
        let mut found =
            self.column_disagreements(1, "the windows executable", statuses);
        for (case, cells) in &self.rows {
            if cells[1] == InventoryCell::Matched && cells[0] != InventoryCell::Matched
            {
                found.push(format!("{case}: matched in windows but not in stepper"));
            }
        }
        found
    }

    fn column_disagreements(
        &self,
        column: usize,
        subject: &str,
        statuses: &[(String, NativeStatus)],
    ) -> Vec<String> {
        let mut found = Vec::new();
        for (case, status) in statuses {
            let Some((_, cells)) = self.rows.iter().find(|(row, _)| row == case) else {
                continue;
            };
            let Some(recorded) = cells.get(column) else {
                continue;
            };
            match (recorded, status) {
                (InventoryCell::Matched, NativeStatus::Matched) => {}
                (InventoryCell::Matched, NativeStatus::Pending(package)) => {
                    found.push(format!(
                        "{case}: marked matched, but {subject} is pending {package}"
                    ))
                }
                (InventoryCell::Matched, NativeStatus::Failed { reason }) => found
                    .push(format!(
                        "{case}: marked matched, but {subject} fails: {reason}"
                    )),
                (InventoryCell::Pending(package), NativeStatus::Matched) => found.push(
                    format!("{case}: marked pending {package}, but {subject} matches"),
                ),
                (InventoryCell::Pending(recorded), NativeStatus::Pending(actual)) => {
                    if recorded != actual {
                        found.push(format!(
                            "{case}: marked pending {recorded}, but {subject} is pending {actual}"
                        ));
                    }
                }
                (InventoryCell::Pending(package), NativeStatus::Failed { reason }) => {
                    found.push(format!(
                        "{case}: marked pending {package}, but {subject} fails: {reason}"
                    ));
                }
            }
        }
        found
    }
}
