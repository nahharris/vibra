/// What the interpreter's counters reported for a program.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct InterpreterExact {
    /// Values built that the memory accounting counts.
    pub allocations: u64,
    /// The most memory held at once, in the machine's own accounting.
    pub peak_bytes: u64,
    /// Expressions reduced.
    pub reductions: u64,
}

/// What the Wasm backend reported for a program.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct WasmExact {
    /// The size of the emitted module.
    pub module_bytes: u64,
    /// Allocations the module's allocator made.
    pub allocations: u64,
    /// The largest live arena size, in bytes, after any allocation.
    pub peak_live_bytes: u64,
    /// Wasmtime fuel the run burned.
    pub fuel: u64,
}

/// The exact metrics of one program.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Exact {
    /// The program's name.
    pub program: String,
    /// The interpreter's metrics.
    pub interpreter: InterpreterExact,
    /// The Wasm backend's metrics.
    pub wasm: WasmExact,
}

/// The median wall time of one program, in microseconds, in each backend.
