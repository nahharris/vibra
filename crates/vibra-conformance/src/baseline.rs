/// The fewest runs a recorded median is taken over.
pub const MIN_RUNS: usize = 11;

/// How a program is found and run.
#[derive(Clone, Copy, Debug)]
enum Kind {
    /// A single `.vib` source whose entry runs.
    Source(&'static str),
    /// The entry of the one binary target of a workspace.
    Workspace(&'static str),
    /// The tests of a workspace whose name contains `select` (all of them when
    /// it is empty), each run in a fresh instance.
    Tests {
        root: &'static str,
        select: &'static str,
    },
}

/// One program of the baseline.
#[derive(Clone, Copy, Debug)]
pub struct Program {
    /// The program's name in the document.
    pub name: &'static str,
    /// What the program does and measures.
    pub what: &'static str,
    kind: Kind,
}

impl Program {
    /// A program that is one `.vib` source at `path` below the root, whose entry
    /// runs. The baseline lists none of its own this way; a host test builds one
    /// to show that a changed or failing program is noticed.
    #[must_use]
    pub const fn source(
        name: &'static str,
        what: &'static str,
        path: &'static str,
    ) -> Self {
        Self {
            name,
            what,
            kind: Kind::Source(path),
        }
    }
}

