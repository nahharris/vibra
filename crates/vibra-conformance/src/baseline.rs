/// A decoded `@perf-baseline.v1` document.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Baseline {
    /// The exact metrics, in program order.
    pub exact: Vec<Exact>,
    /// The informational medians.
    pub informational: Informational,
}

// -- Preparing a program -----------------------------------------------------

enum Work {
    Entry(Box<CheckedProgram>),
    Tests {
        /// Every test that ran, in canonical discovery order: the module's
        /// test positions.
        programs: Vec<CheckedProgram>,
        /// The positions this program runs.
        selected: Vec<usize>,
    },
}

struct Prepared {
    name: &'static str,
    work: Work,
}

fn prepare(root: &Path, program: &Program) -> Result<Prepared, String> {
    let fail = |message: String| format!("program `{}`: {message}", program.name);
    let stdlib = vibra_types::load_stdlib()
        .map_err(|error| fail(format!("the standard library: {error}")))?;
    let work = match program.kind {
        Kind::Source(path) => {
            let text = std::fs::read_to_string(root.join(path))
                .map_err(|error| fail(format!("{path}: {error}")))?;
            // The one import a single source may carry is the bootstrap text module,
            // checked as the corpus checks it.
            let checked = if text.contains("(import text @std.text)") {
                vibra_types::check_bootstrap_text_import(&stdlib, "input.vib", &text)
            } else {
                vibra_types::check_source("input.vib", &text)
            };
            let Some(checked_program) =
                checked.program().filter(|_| checked.accepted())
            else {
                return Err(fail(format!(
                    "{path} is not accepted: {:?}",
                    checked.diagnostics()
                )));
            };
            Work::Entry(Box::new(checked_program.clone()))
        }
        Kind::Workspace(path) => {
            let snapshot = WorkspaceSnapshot::load_confined(root.join(path))
                .map_err(|error| fail(format!("{path}: {error}")))?;
            let target = snapshot
                .project()
                .project()
                .targets()
                .iter()
                .find(|target| target.kind() == TargetKind::Bin)
                .ok_or_else(|| fail(format!("{path} has no binary target")))?;
            let checked = vibra_workspace::semantic::check_all_with_bootstrap(
                &snapshot,
                Some(&stdlib),
            );
            if checked.status() != CheckStatus::Accepted {
                return Err(fail(format!(
                    "{path} is not accepted: {:?}",
                    checked.diagnostics()
                )));
            }
            let entry = checked
                .program_for_target(target)
                .ok_or_else(|| fail(format!("{path} has no checked entry")))?;
            Work::Entry(Box::new(entry.clone()))
        }
        Kind::Tests {
            root: tests_root,
            select,
        } => {
            let snapshot = WorkspaceSnapshot::load_confined(root.join(tests_root))
                .map_err(|error| fail(format!("{tests_root}: {error}")))?;
            let result =
                vibra_workspace::semantic::run_tests(&snapshot, None, Some(&stdlib));
            if result.status() != TestSuiteStatus::Ok {
                return Err(fail(format!(
                    "the tests of {tests_root} do not pass: {:?} {:?}",
                    result.status(),
                    result.diagnostics()
                )));
            }
            let mut programs = Vec::new();
            let mut selected = Vec::new();
            for item in result.items() {
                let Some(checked) = item.program() else {
                    continue;
                };
                if item.name().contains(select) {
                    selected.push(programs.len());
                }
                programs.push(checked.clone());
            }
            if selected.is_empty() {
                return Err(fail(format!(
                    "no test of {tests_root} matches `{select}`"
                )));
            }
            Work::Tests { programs, selected }
        }
    };
    Ok(Prepared {
        name: program.name,
        work,
    })
}

fn count(value: usize) -> u64 {
    u64::try_from(value).unwrap_or(u64::MAX)
}

// -- The interpreter ---------------------------------------------------------

fn run_interpreter(prepared: &Prepared) -> Result<InterpreterExact, String> {
    let fail = |message: String| {
        format!("program `{}`: interpreter: {message}", prepared.name)
    };
    let budget = interpreter_budget();
    match &prepared.work {
        Work::Entry(program) => {
            let mut provider = WorldProvider::new(&HostWorld::default());
            let execution = vibra_interp::Interpreter::run_with_host(
                program,
                budget,
                &mut provider,
            )
            .map_err(|error| fail(error.to_string()))?;
            if execution.program_failed() {
                return Err(fail("the entry returned err".to_owned()));
            }
            Ok(InterpreterExact {
                allocations: count(execution.allocation_count()),
                peak_bytes: count(execution.peak_memory_bytes()),
                reductions: count(execution.reduction_count()),
            })
        }
        Work::Tests { programs, selected } => {
            let mut total = InterpreterExact {
                allocations: 0,
                peak_bytes: 0,
                reductions: 0,
            };
            for index in selected {
                let program = programs
                    .get(*index)
                    .ok_or_else(|| fail("a selected test is missing".to_owned()))?;
                let mut provider = WorldProvider::new(&HostWorld::default());
                let execution = vibra_interp::Interpreter::run_test_with_host(
                    program,
                    budget,
                    &mut provider,
                )
                .map_err(|error| fail(error.to_string()))?;
                if execution.assertion_failure().is_some() {
                    return Err(fail("a test's assertion failed".to_owned()));
                }
                total.allocations += count(execution.allocation_count());
                total.reductions += count(execution.reduction_count());
                total.peak_bytes =
                    total.peak_bytes.max(count(execution.peak_memory_bytes()));
            }
            Ok(total)
        }
    }
}

// -- The Wasm backend --------------------------------------------------------

fn emit_bytes(prepared: &Prepared, measured: bool) -> Result<Vec<u8>, String> {
    let fail =
        |message: String| format!("program `{}`: wasm: {message}", prepared.name);
    let module = match &prepared.work {
        Work::Entry(program) => {
            if measured {
                vibra_wasm::emit_measured(program)
            } else {
                vibra_wasm::emit(program)
            }
        }
        Work::Tests { programs, .. } => {
            let first = programs
                .first()
                .ok_or_else(|| fail("no test to lower".to_owned()))?;
            let entries = programs
                .iter()
                .map(CheckedProgram::entry_index)
                .collect::<Vec<_>>();
            if measured {
                vibra_wasm::emit_tests_measured(first, &entries)
            } else {
                vibra_wasm::emit_tests(first, &entries)
            }
        }
    }
    .map_err(|error| fail(format!("does not lower: {error}")))?;
    Ok(module.into_bytes())
}

/// Runs the program's module in a fresh instance of `runner` once per test
/// position (once for an entry), and calls `each` on every instance that
/// completed.
fn run_wasm(
    runner: &Runner,
    bytes: &[u8],
    prepared: &Prepared,
    mut each: impl FnMut(&mut Instance) -> Result<(), String>,
) -> Result<(), String> {
    let fail =
        |message: String| format!("program `{}`: wasm: {message}", prepared.name);
    let positions: Vec<Option<u32>> = match &prepared.work {
        Work::Entry(_) => vec![None],
        Work::Tests { selected, .. } => selected
            .iter()
            .map(|index| u32::try_from(*index).map(Some))
            .collect::<Result<_, _>>()
            .map_err(|_| fail("a test position does not fit 32 bits".to_owned()))?,
    };
    for position in positions {
        let provider = Box::new(WorldProvider::new(&HostWorld::default()));
        let started = runner
            .start_with_host(bytes, provider)
            .map_err(|error| fail(error.to_string()))?;
        let Started::Ready(mut instance) = started else {
            return Err(fail("the module's memory exceeds the limit".to_owned()));
        };
        let outcome = match position {
            None => instance.call_entry(),
            Some(index) => instance.call_test(index),
        }
        .map_err(|error| fail(error.to_string()))?;
        if !matches!(outcome, Outcome::Completed { .. }) {
            return Err(fail(format!("did not complete: {outcome:?}")));
        }
        each(&mut instance)?;
    }
    Ok(())
}

fn read_counter(instance: &mut Instance, offset: u32) -> Result<u64, String> {
    let bytes = instance
        .read_memory_for_tests(offset, 8)
        .map_err(|outcome| format!("{outcome:?}"))?;
    let word: [u8; 8] = bytes
        .try_into()
        .map_err(|_| "a counter is not eight bytes".to_owned())?;
    Ok(u64::from_le_bytes(word))
}

fn run_wasm_exact(prepared: &Prepared) -> Result<WasmExact, String> {
    let plain = emit_bytes(prepared, false)?;
    let measured = emit_bytes(prepared, true)?;
    // Fuel is metered by a runner of its own. The conformance runner meters none.
    let metering =
        Runner::with_fuel(wasm_memory_limit()).map_err(|error| error.to_string())?;
    let mut fuel = 0_u64;
    run_wasm(&metering, &plain, prepared, |instance| {
        fuel += instance
            .fuel_consumed()
            .ok_or_else(|| "the runner metered no fuel".to_owned())?;
        Ok(())
    })?;
    let counting =
        Runner::new(wasm_memory_limit()).map_err(|error| error.to_string())?;
    let mut allocations = 0_u64;
    let mut peak_live_bytes = 0_u64;
    run_wasm(&counting, &measured, prepared, |instance| {
        allocations += read_counter(instance, state::ALLOC_COUNT)?;
        peak_live_bytes =
            peak_live_bytes.max(read_counter(instance, state::LIVE_PEAK)?);
        Ok(())
    })?;
    Ok(WasmExact {
        module_bytes: count(plain.len()),
        allocations,
        peak_live_bytes,
        fuel,
    })
}

// -- Measuring ---------------------------------------------------------------

/// Runs one program in both backends and returns its exact metrics.
///
/// # Errors
///
/// A message naming the program when it does not check, lower, complete, or pass.
pub fn measure_program(root: &Path, program: &Program) -> Result<Exact, String> {
    let prepared = prepare(root, program)?;
    Ok(Exact {
        program: prepared.name.to_owned(),
        interpreter: run_interpreter(&prepared)?,
        wasm: run_wasm_exact(&prepared)?,
    })
}

fn prepare_all(root: &Path, programs: &[Program]) -> Result<Vec<Prepared>, String> {
    programs
        .iter()
        .map(|program| prepare(root, program))
        .collect()
}

/// Runs every program in both backends and returns the exact metrics, in the
/// order of [`PROGRAMS`]. Two calls give the same result. The programs are
/// independent, so each runs on a thread of its own and the call takes as long as
/// the slowest one.
///
/// # Errors
///
/// A message naming the program that did not check, lower, complete, or pass.
pub fn measure_exact(root: &Path) -> Result<Vec<Exact>, String> {
    std::thread::scope(|scope| {
        let handles = PROGRAMS
            .iter()
            .map(|program| {
                (program, scope.spawn(move || measure_program(root, program)))
            })
            .collect::<Vec<_>>();
        handles
            .into_iter()
            .map(|(program, handle)| {
                handle.join().unwrap_or_else(|_| {
                    Err(format!("program `{}`: panicked", program.name))
                })
            })
            .collect()
    })
}

fn median_micros(
    runs: usize,
    mut run: impl FnMut() -> Result<(), String>,
) -> Result<u64, String> {
    let mut samples = Vec::with_capacity(runs);
    for _ in 0..runs {
        let start = Instant::now();
        run()?;
        samples.push(start.elapsed().as_micros());
    }
    samples.sort_unstable();
    let middle = samples.get(samples.len() / 2).copied().unwrap_or(0);
    Ok(u64::try_from(middle).unwrap_or(u64::MAX))
}

/// Measures both halves: the exact metrics, and the median wall time over
/// `runs` runs of each program in each backend. The interpreter's time is one
/// run of the checked program; the Wasm backend's is one validation,
/// compilation, instantiation, and run of the emitted module under the
/// conformance runner's configuration (no fuel).
///
/// # Errors
///
/// A message naming the program that failed, or that `runs` is below
/// [`MIN_RUNS`].
pub fn measure(root: &Path, runs: usize) -> Result<Baseline, String> {
    measure_programs(root, &PROGRAMS, runs)
}

/// [`measure`] over `programs`, which a host test narrows to the cheap ones.
///
/// # Errors
///
/// A message naming the program that failed, or that `runs` is below
/// [`MIN_RUNS`].
pub fn measure_programs(
    root: &Path,
    programs: &[Program],
    runs: usize,
) -> Result<Baseline, String> {
    if runs < MIN_RUNS {
        return Err(format!(
            "a recorded median needs at least {MIN_RUNS} runs, not {runs}"
        ));
    }
    let prepared = prepare_all(root, programs)?;
    let plain = Runner::new(wasm_memory_limit()).map_err(|error| error.to_string())?;
    let mut exact = Vec::new();
    let mut medians = Vec::new();
    for program in &prepared {
        exact.push(Exact {
            program: program.name.to_owned(),
            interpreter: run_interpreter(program)?,
            wasm: run_wasm_exact(program)?,
        });
        let bytes = emit_bytes(program, false)?;
        medians.push(Median {
            program: program.name.to_owned(),
            interpreter: median_micros(runs, || run_interpreter(program).map(|_| ()))?,
            wasm: median_micros(runs, || {
                run_wasm(&plain, &bytes, program, |_| Ok(()))
            })?,
        });
    }
    Ok(Baseline {
        exact,
        informational: Informational {
            environment: environment(root),
            runs: u32::try_from(runs).unwrap_or(u32::MAX),
            medians,
        },
    })
}

// -- The environment ---------------------------------------------------------

fn command_output(program: &str, args: &[&str]) -> Option<String> {
    let output = Command::new(program).args(args).output().ok()?;
    let text = String::from_utf8(output.stdout).ok()?;
    let line = text.lines().find(|line| !line.trim().is_empty())?;
    Some(line.trim().to_owned())
}

fn cpu_model() -> String {
    if let Ok(model) = std::env::var("PROCESSOR_IDENTIFIER") {
        return model;
    }
    if let Ok(info) = std::fs::read_to_string("/proc/cpuinfo")
        && let Some(line) = info.lines().find(|line| line.starts_with("model name"))
        && let Some((_, model)) = line.split_once(':')
    {
        return model.trim().to_owned();
    }
    command_output("sysctl", &["-n", "machdep.cpu.brand_string"])
        .unwrap_or_else(|| "unknown".to_owned())
}

fn os_version() -> String {
    let found = match std::env::consts::OS {
        "windows" => command_output("cmd", &["/C", "ver"]),
        "macos" => command_output("sw_vers", &["-productVersion"]),
        _ => std::fs::read_to_string("/etc/os-release")
            .ok()
            .and_then(|text| {
                text.lines()
                    .find_map(|line| line.strip_prefix("PRETTY_NAME="))
                    .map(|name| name.trim_matches('"').to_owned())
            }),
    };
    found.unwrap_or_else(|| "unknown".to_owned())
}

fn locked_wasmtime(root: &Path) -> String {
    let Ok(lock) = std::fs::read_to_string(root.join("Cargo.lock")) else {
        return "unknown".to_owned();
    };
    let mut lines = lock.lines();
    while let Some(line) = lines.next() {
        if line == "name = \"wasmtime\""
            && let Some(version) = lines
                .next()
                .and_then(|next| next.strip_prefix("version = "))
        {
            return version.trim_matches('"').to_owned();
        }
    }
    "unknown".to_owned()
}

fn environment(root: &Path) -> Environment {
    Environment {
        os: std::env::consts::OS.to_owned(),
        os_version: os_version(),
        arch: std::env::consts::ARCH.to_owned(),
        cpu: cpu_model(),
        logical_cpus: std::thread::available_parallelism()
            .map_or(0, |cpus| u32::try_from(cpus.get()).unwrap_or(u32::MAX)),
        rust: command_output("rustc", &["--version"])
            .unwrap_or_else(|| "unknown".to_owned()),
        wasmtime: locked_wasmtime(root),
        profile: if cfg!(debug_assertions) {
            "debug"
        } else {
            "release"
        }
        .to_owned(),
    }
}

// -- The document ------------------------------------------------------------

impl Baseline {
    /// The canonical `@perf-baseline.v1` text: written by the tool, formatted by
    /// the repository's formatter, never edited by hand.
    ///
    /// # Errors
    ///
    /// A message when the text does not format, which would be a defect here.
    pub fn render(&self) -> Result<String, String> {
        let mut text = format!(
            "; Generated by `cargo run -p vibra-conformance --bin perf-baseline -- --write`; never edited by hand.
; The exact metrics are checked by CI; the informational half is not.
(record format: @{FORMAT} exact: (array"
        );
        for entry in &self.exact {
            let _ = write!(
                text,
                " (record program: @{} interpreter: (record allocations: {}u64 peak-bytes: {}u64 reductions: {}u64) wasm: (record module-bytes: {}u64 allocations: {}u64 peak-live-bytes: {}u64 fuel: {}u64))",
                entry.program,
                entry.interpreter.allocations,
                entry.interpreter.peak_bytes,
                entry.interpreter.reductions,
                entry.wasm.module_bytes,
                entry.wasm.allocations,
                entry.wasm.peak_live_bytes,
                entry.wasm.fuel,
            );
        }
        let info = &self.informational;
        let env = &info.environment;
        let _ = write!(
            text,
            ") informational: (record environment: (record os: {} os-version: {} arch: {} cpu: {} logical-cpus: {}u32 rust: {} wasmtime: {} profile: @{}) runs: {}u32 median-microseconds: (array",
            canonical_string(&env.os),
            canonical_string(&env.os_version),
            canonical_string(&env.arch),
            canonical_string(&env.cpu),
            env.logical_cpus,
            canonical_string(&env.rust),
            canonical_string(&env.wasmtime),
            env.profile,
            info.runs,
        );
        for median in &info.medians {
            let _ = write!(
                text,
                " (record program: @{} interpreter: {}u64 wasm: {}u64)",
                median.program, median.interpreter, median.wasm
            );
        }
        text.push_str(")))\n");
        vibra_fmt::format_source("performance-baseline.vibon", &text)
            .map_err(|error| format!("the baseline does not format: {error:?}"))
    }

    /// Decodes a `@perf-baseline.v1` document.
    ///
    /// # Errors
    ///
    /// A message naming what is not a baseline document.
    pub fn parse(text: &str) -> Result<Self, String> {
        let document = vibra_syntax::parse_data("performance-baseline.vibon", text)
            .map_err(|error| error.to_string())?;
        let root = document
            .data()
            .filter(|_| document.accepted())
            .ok_or_else(|| "the document is not valid VIBON".to_owned())?;
        let format = atom(field(root, "format")?)?;
        if format != FORMAT {
            return Err(format!("format is @{format}, not @{FORMAT}"));
        }
        let exact = array(field(root, "exact")?)?
            .into_iter()
            .map(decode_exact)
            .collect::<Result<Vec<_>, _>>()?;
        let informational = field(root, "informational")?;
        let env = field(informational, "environment")?;
        let environment = Environment {
            os: string(field(env, "os")?)?,
            os_version: string(field(env, "os-version")?)?,
            arch: string(field(env, "arch")?)?,
            cpu: string(field(env, "cpu")?)?,
            logical_cpus: u32::try_from(integer(field(env, "logical-cpus")?, "u32")?)
                .map_err(|_| "logical-cpus does not fit".to_owned())?,
            rust: string(field(env, "rust")?)?,
            wasmtime: string(field(env, "wasmtime")?)?,
            profile: atom(field(env, "profile")?)?,
        };
        let medians = array(field(informational, "median-microseconds")?)?
            .into_iter()
            .map(|node| {
                Ok(Median {
                    program: atom(field(node, "program")?)?,
                    interpreter: integer(field(node, "interpreter")?, "u64")?,
                    wasm: integer(field(node, "wasm")?, "u64")?,
                })
            })
            .collect::<Result<Vec<_>, String>>()?;
        Ok(Self {
            exact,
            informational: Informational {
                environment,
                runs: u32::try_from(integer(field(informational, "runs")?, "u32")?)
                    .map_err(|_| "runs does not fit".to_owned())?,
                medians,
            },
        })
    }
}

fn decode_exact(node: &DataNode) -> Result<Exact, String> {
    let interpreter = field(node, "interpreter")?;
    let wasm = field(node, "wasm")?;
    let number = |parent: &DataNode, label: &str| integer(field(parent, label)?, "u64");
    Ok(Exact {
        program: atom(field(node, "program")?)?,
        interpreter: InterpreterExact {
            allocations: number(interpreter, "allocations")?,
            peak_bytes: number(interpreter, "peak-bytes")?,
            reductions: number(interpreter, "reductions")?,
        },
        wasm: WasmExact {
            module_bytes: number(wasm, "module-bytes")?,
            allocations: number(wasm, "allocations")?,
            peak_live_bytes: number(wasm, "peak-live-bytes")?,
            fuel: number(wasm, "fuel")?,
        },
    })
}

fn field<'a>(node: &'a DataNode, label: &str) -> Result<&'a DataNode, String> {
    let DataValue::Record(fields) = node.value() else {
        return Err(format!("expected a record holding `{label}`"));
    };
    fields
        .iter()
        .find(|field| field.label().value() == label)
        .map(vibra_syntax::DataField::value)
        .ok_or_else(|| format!("the record has no field `{label}`"))
}

fn array(node: &DataNode) -> Result<Vec<&DataNode>, String> {
    match node.value() {
        DataValue::Array(items) => Ok(items.iter().collect()),
        _ => Err("expected an array".to_owned()),
    }
}

fn atom(node: &DataNode) -> Result<String, String> {
    match node.value() {
        DataValue::Atom(name) => Ok(name.value().trim_start_matches('@').to_owned()),
        _ => Err("expected an atom".to_owned()),
    }
}

fn string(node: &DataNode) -> Result<String, String> {
    match node.value() {
        DataValue::Literal(Literal::String(text)) => Ok(text.value().to_owned()),
        _ => Err("expected a string".to_owned()),
    }
}

fn integer(node: &DataNode, suffix: &str) -> Result<u64, String> {
    match node.value() {
        DataValue::Literal(Literal::Integer(number)) => number
            .raw()
            .strip_suffix(suffix)
            .and_then(|digits| digits.parse().ok())
            .ok_or_else(|| format!("expected an unsigned `{suffix}` integer")),
        _ => Err("expected an integer".to_owned()),
    }
}

// -- Comparing ---------------------------------------------------------------

fn metrics(entry: &Exact) -> [(&'static str, u64); 7] {
    [
        ("interpreter allocations", entry.interpreter.allocations),
        ("interpreter peak bytes", entry.interpreter.peak_bytes),
        ("interpreter reductions", entry.interpreter.reductions),
        ("wasm module bytes", entry.wasm.module_bytes),
        ("wasm allocations", entry.wasm.allocations),
        ("wasm peak live bytes", entry.wasm.peak_live_bytes),
        ("wasm fuel", entry.wasm.fuel),
    ]
}

/// Every difference between the recorded exact metrics and the measured ones, as
/// a message that names the program and the metric. Empty when they agree. The
/// medians never take part.
#[must_use]
pub fn differences(recorded: &[Exact], measured: &[Exact]) -> Vec<String> {
    let mut found = Vec::new();
    for now in measured {
        let Some(before) = recorded.iter().find(|entry| entry.program == now.program)
        else {
            found.push(format!(
                "program `{}` is measured but missing from the recorded baseline",
                now.program
            ));
            continue;
        };
        for ((label, was), (_, is)) in metrics(before).into_iter().zip(metrics(now)) {
            if was != is {
                found.push(format!(
                    "program `{}`: {label}: recorded {was}, measured {is}",
                    now.program
                ));
            }
        }
    }
    for before in recorded {
        if !measured.iter().any(|entry| entry.program == before.program) {
            found.push(format!(
                "program `{}` is recorded but no longer measured",
                before.program
            ));
        }
    }
    found
}
