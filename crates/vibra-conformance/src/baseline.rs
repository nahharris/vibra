//! The interpreter and unoptimized-WebAssembly performance baseline (milestone 4
//! Step 21; ledger D29.1).
//!
//! The baseline is a named list of ten programs, each run in the reference
//! interpreter and in the Wasm backend. For each program and backend it records
//! two kinds of number.
//!
//! **Exact metrics** are deterministic: two runs, on any machine, give the same
//! numbers. A host test regenerates them and fails on any difference from the
//! checked-in `docs/roadmap/milestone-4/performance-baseline.vibon`, so a change
//! that moves one is reviewed as a baseline change.
//!
//! | Backend | Metric | Where it comes from |
//! | --- | --- | --- |
//! | Wasm | module bytes | the emitted module (`vibra_wasm::emit`), a pure function of the program |
//! | Wasm | fuel | Wasmtime fuel, metered by a runner built with `Runner::with_fuel`; the conformance runner meters none |
//! | Wasm | allocations, peak live bytes | the counters a module emitted for measurement (`vibra_wasm::emit_measured`) keeps in two state fields |
//! | interpreter | allocations, peak bytes, reductions | the machine's own counters (`Execution::allocation_count` and the rest) |
//!
//! **Wall-time medians** are recorded beside them as information and never
//! compared: they depend on the machine, so the document names the machine.
//!
//! The document is generated by `perf-baseline --write` and never edited by
//! hand.

